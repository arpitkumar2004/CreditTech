"""Unit tests for the Zero-Downtime Migration CI Gate (scripts/check_migrations.py)."""

from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest
from alembic.util import AutogenerateDiffsDetected

from scripts.check_migrations import (
    check_migration_safety,
    check_schema_sync,
    main,
)


def test_schema_check_passes_on_current_db() -> None:
    """Verifies that schema check passes when the database matches the Alembic head revision."""
    assert check_schema_sync(config_path="alembic.ini") is True


def test_schema_check_fails_on_detected_diffs() -> None:
    """Verifies that schema check returns False when Alembic detects autogenerate diffs."""
    mock_rev_ctx = MagicMock()
    with patch(
        "alembic.command.check",
        side_effect=AutogenerateDiffsDetected(
            "New upgrade operations detected",
            revision_context=mock_rev_ctx,
            diffs=[("add_column", "table", "col")],
        ),
    ):
        assert check_schema_sync(config_path="alembic.ini") is False


def test_schema_check_fails_on_missing_config(tmp_path: Path) -> None:
    """Verifies that schema check returns False if the alembic config file is missing."""
    missing_config = tmp_path / "nonexistent.ini"
    assert check_schema_sync(config_path=missing_config) is False


def test_safety_check_passes_on_baseline_migration() -> None:
    """Verifies that safety check cleanly passes on the existing baseline schema migration."""
    errors = check_migration_safety(
        versions_dir="alembic/versions",
        baseline_revisions=("14323a45982d",),
    )
    assert errors == []


def test_safety_check_flags_unsafe_add_column_not_nullable_without_default(tmp_path: Path) -> None:
    """Verifies that op.add_column with nullable=False and no server_default is flagged as unsafe."""
    mig_file = tmp_path / "test_unsafe_add_col.py"
    mig_file.write_text(
        """
import sqlalchemy as sa
from alembic import op

revision = "rev_unsafe_01"

def upgrade() -> None:
    op.add_column("borrowers", sa.Column("secondary_phone", sa.String(20), nullable=False))
""",
        encoding="utf-8",
    )
    errors = check_migration_safety(versions_dir=tmp_path, baseline_revisions=())
    assert len(errors) == 1
    assert "op.add_column" in errors[0]
    assert "nullable=False" in errors[0]
    assert "server_default" in errors[0]


