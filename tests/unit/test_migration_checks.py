def test_cli_flags(monkeypatch: pytest.MonkeyPatch) -> None:
    """Verifies CLI flag behavior for --check-schema-only and --check-safety-only."""
    schema_called = False
    safety_called = False

    def fake_schema_sync(config_path: str = "alembic.ini") -> bool:
        nonlocal schema_called
        schema_called = True
        return True

    def fake_safety(
        versions_dir: str = "alembic/versions",
        baseline_revisions: tuple[str, ...] = ("14323a45982d",),
    ) -> list[str]:
        nonlocal safety_called
        safety_called = True
        return []

    monkeypatch.setattr("scripts.check_migrations.check_schema_sync", fake_schema_sync)
    monkeypatch.setattr("scripts.check_migrations.check_migration_safety", fake_safety)

    # 1. Default: runs both
    schema_called = False
    safety_called = False
    exit_code = main([])
    assert exit_code == 0
    assert schema_called is True
    assert safety_called is True

    # 2. Schema only
    schema_called = False
    safety_called = False
    exit_code = main(["--check-schema-only"])
    assert exit_code == 0
    assert schema_called is True
    assert safety_called is False

    # 3. Safety only
    schema_called = False
    safety_called = False
    exit_code = main(["--check-safety-only"])
    assert exit_code == 0
    assert schema_called is False
    assert safety_called is True


def test_cli_failure_exit_codes(monkeypatch: pytest.MonkeyPatch) -> None:
    """Verifies that main() returns exit code 1 if either check fails."""
    # Schema check fails
    monkeypatch.setattr("scripts.check_migrations.check_schema_sync", lambda *args, **kwargs: False)
    monkeypatch.setattr("scripts.check_migrations.check_migration_safety", lambda *args, **kwargs: [])
    assert main(["--check-schema-only"]) == 1

    # Safety check fails
    monkeypatch.setattr("scripts.check_migrations.check_schema_sync", lambda *args, **kwargs: True)
    monkeypatch.setattr(
        "scripts.check_migrations.check_migration_safety",
        lambda *args, **kwargs: ["error: unsafe op.drop_table"],
    )
    assert main(["--check-safety-only"]) == 1
